#!/usr/bin/env python3
"""Writes libCoreGraphics' stubs and export lists from symbols.txt.

Every symbol in symbols.txt that nothing implements yet gets a stub that
reports the gap (silica_cg_unimplemented) and returns zero, so the library
exports the whole API from the start and clients link and load against it.

What's implemented is read from the sources, so the stubs can't drift from
them: a Swift function marked `@c @implementation` or `@c(Name)` in
Sources/SilicaCoreGraphicsABI, or a constant defined in
Sources/CSilicaCoreGraphics/constants.c.

Writes:
  Sources/CSilicaCoreGraphics/gen/stubs.c     the stubs
  Scripts/CoreGraphics/exports.map           ELF version script
  Scripts/CoreGraphics/exports.txt           Mach-O exported symbols list
  Scripts/CoreGraphics/macho-aliases.ld      ELF aliases under Mach-O names (`_CGPathCreateMutable`), for Perry

    python3 Scripts/CoreGraphics/gen_stubs.py           # writes the files
    python3 Scripts/CoreGraphics/gen_stubs.py --check   # fails if they're stale
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SYMBOLS = ROOT / "Scripts" / "CoreGraphics" / "symbols.txt"
SWIFT_SOURCES = ROOT / "Sources" / "SilicaCoreGraphicsABI"
CONSTANTS = ROOT / "Sources" / "CSilicaCoreGraphics" / "constants.c"
STUBS = ROOT / "Sources" / "CSilicaCoreGraphics" / "gen" / "stubs.c"
VERSION_SCRIPT = ROOT / "Scripts" / "CoreGraphics" / "exports.map"
MACHO_EXPORTS = ROOT / "Scripts" / "CoreGraphics" / "exports.txt"
MACHO_ALIASES = ROOT / "Scripts" / "CoreGraphics" / "macho-aliases.ld"


def symbols():
    functions, data = [], []
    for line in SYMBOLS.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, *kind = line.split()
        (data if kind == ["data"] else functions).append(name)
    return functions, data


def implemented():
    names = set()
    for source in sorted(SWIFT_SOURCES.glob("*.swift")):
        text = source.read_text()
        names.update(re.findall(r"@c\s+@implementation\s+(?:public\s+)?func\s+(\w+)", text))
        names.update(re.findall(r"@c\((\w+)\)", text))
    names.update(re.findall(r"^const\s+\w+\s+(\w+)\s*=", CONSTANTS.read_text(), re.MULTILINE))
    return names


def outputs():
    functions, data = symbols()
    done = implemented()
    unknown = sorted(done - set(functions) - set(data))
    if unknown:
        sys.exit("implemented but not in symbols.txt: " + ", ".join(unknown))
    missing_data = sorted(set(data) - done)
    if missing_data:
        sys.exit("data symbols must be defined in constants.c: " + ", ".join(missing_data))
    stubs = [name for name in functions if name not in done]

    stub_lines = [
        "/* stubs.c - generated by Scripts/CoreGraphics/gen_stubs.py; do not edit.",
        " *",
        f" * {len(stubs)} of the {len(functions)} functions in symbols.txt aren't implemented",
        " * yet. Each stub reports the gap and returns zero, so clients link and load",
        " * against the whole API. Implementing a function in Swift retires its stub",
        " * when this file is generated again. */",
        "",
        '#include "../silica_cg_internal.h"',
        "",
    ]
    for name in stubs:
        stub_lines.append(f"long {name}(void) {{ silica_cg_unimplemented(__func__); return 0; }}")
    everything = sorted(functions + data)
    version = ["/* generated by Scripts/CoreGraphics/gen_stubs.py; do not edit */", "{", "  global:"]
    version += [f"    {name};" for name in everything]
    version += [f"    _{name};" for name in everything]
    version += ["    /* the Swift API, for runtimes that supply their own objects (Perry) */",
                '    $s21SilicaCoreGraphicsABI*;']
    version += ["  local:", "    *;", "};"]
    macho = [f"_{name}" for name in everything]
    aliases = ["/* generated by Scripts/CoreGraphics/gen_stubs.py; do not edit",
               " * Each symbol again under its Mach-O name, as Darwin code links it. */"]
    aliases += [f"_{name} = {name};" for name in everything]
    return {
        STUBS: "\n".join(stub_lines) + "\n",
        VERSION_SCRIPT: "\n".join(version) + "\n",
        MACHO_EXPORTS: "\n".join(macho) + "\n",
        MACHO_ALIASES: "\n".join(aliases) + "\n",
    }, len(stubs), len(functions)


def main():
    files, stubbed, total = outputs()
    if "--check" in sys.argv:
        stale = [str(path.relative_to(ROOT)) for path, text in files.items()
                 if not path.exists() or path.read_text() != text]
        if stale:
            sys.exit("out of date, run Scripts/CoreGraphics/gen_stubs.py: " + ", ".join(stale))
        return
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"{total - stubbed} of {total} functions implemented, {stubbed} stubbed")


if __name__ == "__main__":
    main()
